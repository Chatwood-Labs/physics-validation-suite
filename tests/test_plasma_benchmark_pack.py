"""Independent source anchors and source-to-subject checks for the example pack.

Table values below were read from publication images, not generated by the
subject under test. These checks qualify the declared reference derivation;
they do not execute or qualify an external production solver.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import sys
from decimal import Decimal, localcontext
from pathlib import Path
from typing import Any

import pytest
import yaml

from pvs import validate_case

PACK = Path(__file__).parents[1] / "benchmark-packs" / "plasma-physics-reference-v1"


@pytest.fixture(scope="module")
def derived_values(tmp_path_factory: pytest.TempPathFactory) -> dict[str, Any]:
    output = tmp_path_factory.mktemp("plasma-equations") / "derived.json"
    subprocess.run(
        [sys.executable, str(PACK / "derive_reference_values.py"), "--output", str(output)],
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(output.read_text(encoding="utf-8"), parse_float=Decimal)


def test_bosch_hale_against_printed_table_viii(derived_values: dict[str, Any]) -> None:
    """18 matching rows from Bosch-Hale p. 625, cm3/s converted to m3/s.

    The oracle is the manually transcribed printed table with its own decimal
    resolution, rather than another evaluation of the same equation.
    Reviewed scan SHA256: 0770dd18e3c91741cbe6ac8837f8a0ab8e54d4fbcbfca868ba8eaac47ac9e38e.
    """
    printed = {
        "0.2": "1.254e-32",
        "0.5": "5.697e-29",
        "1.0": "6.857e-27",
        "1.5": "6.923e-26",
        "2.0": "2.977e-25",
        "2.5": "8.425e-25",
        "3.0": "1.867e-24",
        "4.0": "5.974e-24",
        "5.0": "1.366e-23",
        "6.0": "2.554e-23",
        "8.0": "6.222e-23",
        "10.0": "1.136e-22",
        "12.0": "1.747e-22",
        "15.0": "2.740e-22",
        "20.0": "4.330e-22",
        "30.0": "6.681e-22",
        "40.0": "7.998e-22",
        "50.0": "8.649e-22",
    }
    actual = dict(
        zip(
            derived_values["bosch_hale_dt"]["temperature_kev"],
            derived_values["bosch_hale_dt"]["reactivity_m3_s"],
            strict=True,
        )
    )
    for temperature, text in printed.items():
        reference = Decimal(text)
        # Half the final printed decimal place, not model uncertainty.
        quantum = Decimal(1).scaleb(reference.as_tuple().exponent)
        assert abs(actual[Decimal(temperature)] - reference) <= quantum / 2


def test_nrl_si_values_with_independent_decimal_arithmetic(
    derived_values: dict[str, Any],
) -> None:
    """NRL2023 pp.28,34,58 equations evaluated independently at 60 digits.

    The species-summed equilibration coefficient and explicit SI conversion
    exercise the factor-of-two, harmonic-mass and density-conversion risks.
    """
    with localcontext() as context:
        context.prec = 60
        density_cm3 = Decimal("1e14")
        collision = derived_values["nrl_electron_collision"]
        for temperature, actual in zip(
            collision["temperature_ev"], collision["frequency_s-1"], strict=True
        ):
            coulomb_log = Decimal(24) - (density_cm3.sqrt() / temperature).ln()
            expected = Decimal("2.91e-6") * density_cm3 * coulomb_log / temperature**Decimal(
                "1.5"
            )
            assert abs(actual / expected - 1) < Decimal("2e-14")

        equilibration = derived_values["nrl_dt_equilibration"]
        d_ratio = Decimal("1.9990075012699")
        t_ratio = Decimal("2.99371703403")
        for temperature, actual_rate, actual_delta_time in zip(
            equilibration["temperature_ev"],
            equilibration["frequency_s-1"],
            equilibration["tau_delta_temperature_s"],
            strict=True,
        ):
            coulomb_log = Decimal(24) - (density_cm3.sqrt() / temperature).ln()
            rate = (
                Decimal("3.2e-9")
                * coulomb_log
                * (Decimal("5e13") / d_ratio + Decimal("5e13") / t_ratio)
                / temperature**Decimal("1.5")
            )
            assert abs(actual_rate / rate - 1) < Decimal("2e-14")
            assert abs(actual_delta_time * (2 * rate) - 1) < Decimal("2e-14")

        # SI coefficient = cgs coefficient * (1e-6)^2 * 1e6.
        cases = [("1e20", "1e20", "15000"), ("1.2e20", "1.6e20", "15000")]
        cases.append(("2e20", "2e20", "1000"))
        for (ne, z2ni, temperature), actual in zip(
            cases, derived_values["nrl_bremsstrahlung"]["power_w_m-3"], strict=True
        ):
            expected = (
                Decimal("1.69e-38")
                * Decimal(ne)
                * Decimal(z2ni)
                * Decimal(temperature).sqrt()
            )
            assert abs(actual / expected - 1) < Decimal("2e-14")


@pytest.mark.parametrize(
    ("temperature", "row", "ocr_error", "check_id"),
    [
        ("50_keV", 4, 0.65, "evans-50kev-selected-printed-value"),
        ("100_keV", 3, 0.63, "evans-100kev-selected-printed-value"),
    ],
)
def test_evans_ocr_errors_fail_source_table_comparison(
    tmp_path: Path, temperature: str, row: int, ocr_error: float, check_id: str
) -> None:
    """Re-pinning the historical OCR error must not make it a passing benchmark.

    The former case only compared equations with separate numeric literals;
    its frozen table could contain these source errors and still pass.
    """
    case_root = tmp_path / "case"
    shutil.copytree(PACK, case_root)
    table_path = case_root / "published_table_anchors.json"
    tables = json.loads(table_path.read_text(encoding="utf-8"))
    tables["evans_1973_table_i"]["rows"][temperature][row][1] = ocr_error
    table_path.write_text(json.dumps(tables), encoding="utf-8")
    case_path = case_root / "pvs.yaml"
    case = yaml.safe_load(case_path.read_text(encoding="utf-8"))
    case["artifacts"]["published-tables"]["expected_sha256"] = hashlib.sha256(
        table_path.read_bytes()
    ).hexdigest()
    case["execution"]["command"][0] = sys.executable
    case["package"]["html"] = False
    case["package"]["pdf"] = False
    case_path.write_text(yaml.safe_dump(case, sort_keys=False), encoding="utf-8")
    # Generate the subject output separately so the regression also exercises
    # native Windows, where PVS's supervised command runner is unsupported.
    subprocess.run(
        [sys.executable, "derive_reference_values.py", "--output", "derived_values.json"],
        cwd=case_root,
        check=True,
        capture_output=True,
        text=True,
    )
    outcome = validate_case(case_path, output_dir=tmp_path / "evidence")
    assert outcome.status.value == "FAIL"
    evidence = json.loads((outcome.output_directory / "evidence.json").read_text())
    checks = {item["id"]: item for item in evidence["record"]["checks"]}
    assert checks[check_id]["status"] == "FAIL"
